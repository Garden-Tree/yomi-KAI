"""Google Cloud Text-to-Speech エンジン（APIキー認証）。"""

from __future__ import annotations

import logging

from google.api_core.client_options import ClientOptions
from google.cloud import texttospeech

from . import Speaker

logger = logging.getLogger(__name__)

GOOGLE_SPEAKERS = [
    Speaker("ja-JP-Wavenet-A", "Google女声"),
    Speaker("ja-JP-Wavenet-D", "Google男声"),
]


class GoogleEngine:
    """Google TTS。LINEAR16（WAV ヘッダ付き）で合成する。"""

    def __init__(self, api_key: str) -> None:
        self._client = texttospeech.TextToSpeechClient(client_options=ClientOptions(api_key=api_key))
        self._audio_config = texttospeech.AudioConfig(audio_encoding=texttospeech.AudioEncoding.LINEAR16)

    @property
    def default_speaker(self) -> str:
        return GOOGLE_SPEAKERS[0].name

    def speakers(self) -> list[Speaker]:
        return list(GOOGLE_SPEAKERS)

    def synthesize(self, text: str, speaker: str, speed: float = 1.0) -> bytes:
        voice = texttospeech.VoiceSelectionParams(language_code="ja-JP", name=speaker)
        audio_config = (
            self._audio_config
            if speed == 1.0
            else texttospeech.AudioConfig(audio_encoding=texttospeech.AudioEncoding.LINEAR16, speaking_rate=speed)
        )
        response = self._client.synthesize_speech(
            request={
                "input": texttospeech.SynthesisInput(text=text),
                "voice": voice,
                "audio_config": audio_config,
            }
        )
        logger.info("The audio was successfully generated by Google. (%d bytes)", len(response.audio_content))
        return response.audio_content
